import assert from 'node:assert/strict';
import { chainHealth } from '../backend/static/app/lib/format.js';
import { connectionModel } from '../backend/static/app/views/field.js';
const now=10000;
const entry={id:'a',enabled:true,transport:'hysteria2',hy_ready:true,pin_ok:true,probe_current:true,last_probe:{ts:now-10,ok:true,probe_ok:true}};
assert.equal(chainHealth(entry,now).state,'verified');
assert.equal(chainHealth({...entry,enabled:false},now).state,'off');
assert.equal(chainHealth({...entry,service_state:'inactive'},now).state,'failed');
assert.equal(chainHealth({...entry,needs_repair:true},now).state,'failed');
assert.equal(chainHealth({...entry,hy_ready:false},now).state,'failed');
assert.equal(chainHealth({...entry,probe_current:false},now).state,'unknown');
assert.equal(chainHealth({...entry,last_probe:{...entry.last_probe,ts:now-301}},now).state,'unknown');
assert.equal(chainHealth({...entry,last_probe:{...entry.last_probe,ok:false}},now).state,'failed');
assert.equal(chainHealth({...entry,last_probe:{...entry.last_probe,probe_ok:false}},now).state,'unknown');
const dash={nodes:[{id:'n',enabled:true,service_state:'active'}],chain:{entries:[],probe_revision:'new'}};
const old={checked_at:now-10,chain_revision:'old',nodes:[{node:'n',ok:true}]};
assert.equal(connectionModel(dash,old,'node:n',now).state,'unknown');
assert.equal(connectionModel(dash,{...old,chain_revision:'new'},'node:n',now).state,'verified');
assert.equal(connectionModel({...dash,chain:{entries:[{...entry,probe_current:false}]}},null,'chain:a',now).state,'unknown');
console.log('12 chain health and routing assertions passed');
